  base: string;
  /** Legacy test seam for one direct command base; production uses install authority. */
  commandBase: string;
  /** Override the complete launch spec (tests). */
  launchSpec: HookLaunchSpec;
  /** Override the one pre-write persistent-install authority (tests). */
  installAuthority: () => PersistentInstallAuthority;
