interface OpenCodeHookStatus {
  installed: boolean;
  compatibility: HookCompatibility;
  command?: string;
  launchAvailability?: HookLaunchAvailability;
}

function generatedConstant(source: string, name: string): unknown {
  const match = source.match(new RegExp(`^const ${name} = (.+);$`, "m"));
  if (!match) return undefined;
  try {
    return JSON.parse(match[1]!);
  } catch {
    return undefined;
  }
}

/** Git may materialize a generated JS fixture with CRLF on Windows; line endings are not authorship. */
function normalizedGeneratedSource(source: string): string {
  return source.replaceAll("\r\n", "\n");
}

/** Exact-source classifier: a marker or familiar substring alone never authorizes mutation. */
function readOpenCodeHookStatus(path: string, expectedSource?: string): OpenCodeHookStatus {
  let entry: ReturnType<typeof lstatSync>;
  try {
    entry = lstatSync(path);
  } catch {
    return { installed: false, compatibility: { state: "absent", reason: "plugin file is absent" } };
  }
  if (entry.isSymbolicLink()) {
    return {
      installed: false,
      compatibility: {
        state: "unmanaged",
        reason: "plugin path is a symlink; generated-plugin ownership requires a regular file",
      },
    };
  }
  if (!entry.isFile()) {
    return { installed: false, compatibility: { state: "unmanaged", reason: "plugin path is not a regular file" } };
  }
  const read = readRegularFileTextNoFollowSync(path);
  if (read.state === "missing") {
    return { installed: false, compatibility: { state: "absent", reason: "plugin file is absent" } };
  }
  if (read.state === "unsafe") {
    return { installed: false, compatibility: { state: "unmanaged", reason: "plugin file is unreadable" } };
  }
  const source = read.text;
  const comparableSource = normalizedGeneratedSource(source);
  if (expectedSource !== undefined && comparableSource === normalizedGeneratedSource(expectedSource)) {
    const program = generatedConstant(source, "command");
    const args = generatedConstant(source, "commandArgs");
    return {
      installed: true,
      compatibility: { state: "current", reason: "plugin exactly matches this installation's generator" },
      ...(typeof program === "string" && Array.isArray(args) && args.every((arg) => typeof arg === "string")
        ? { command: [program, ...args].map((token) => renderGeneratedHookToken(token)).join(" ") }
        : {}),
    };
  }

  const command = generatedConstant(source, "command");
  const timeoutMs = generatedConstant(source, "timeoutMs");
  const args = generatedConstant(source, "commandArgs");
  if (
    typeof command === "string" &&
    Array.isArray(args) &&
    args.every((arg) => typeof arg === "string") &&
    typeof timeoutMs === "number" &&
    Number.isInteger(timeoutMs) &&
    comparableSource === buildOpenCodePluginSource(command, args as string[], timeoutMs / 1000)
  ) {
    const launchCommand = [command, ...(args as string[])].map((token) => renderGeneratedHookToken(token)).join(" ");
    const compatibility = classifyHookCommand(launchCommand);
    if (!isOwnedHookCompatibility(compatibility)) return { installed: false, compatibility };
    if (timeoutMs !== HOOK_TIMEOUT_SECONDS * 1000) {
      return {
        installed: true,
        command: launchCommand,
        compatibility: {
          state: "stale",
          reason: "recognized generated plugin has a non-current timeout",
          remedy: `re-run \`${distributionBinName()} hook install\` from the durable global npm installation`,
        },
      };
    }
    return { installed: true, compatibility, command: launchCommand };
  }

  if (
    typeof command === "string" &&
    Array.isArray(args) &&
    args.every((arg) => typeof arg === "string") &&
    typeof timeoutMs === "number" &&
    Number.isInteger(timeoutMs) &&
    (
      comparableSource === buildLegacyOpenCodePluginSource(command, args as string[], timeoutMs / 1000)
      || (
        args.length === 1
        && args[0] === HOOK_SUBCOMMAND
        && timeoutMs === HOOK_TIMEOUT_SECONDS * 1000
        && isPublishedAsliteOpenCodeProgram(command)
        && comparableSource === buildPublishedAsliteOpenCodePluginSource(command)
      )
    )
  ) {
    const compatibility = classifyHookCommand(
      [command, ...(args as string[])].map((token) => renderGeneratedHookToken(token)).join(" "),
    );
    if (!isOwnedHookCompatibility(compatibility)) return { installed: false, compatibility };
    return {
      installed: true,
      compatibility: {
        state: timeoutMs === HOOK_TIMEOUT_SECONDS * 1000 ? "legacy_identity" : "stale",
        reason: "recognized generated OpenCode plugin uses the legacy ASLite identity",
        remedy: `re-run \`${distributionBinName()} hook install\` from the durable global npm installation`,
      },
    };
  }

  if (
    typeof command === "string" &&
    args === undefined &&
    typeof timeoutMs === "number" &&
    Number.isInteger(timeoutMs) &&
    comparableSource === buildLegacySdkOpenCodePluginSource(command, timeoutMs / 1000) &&
    isOwnedHookCompatibility(classifyHookCommand(command))
  ) {
    return {
      installed: true,
      compatibility: {
        state: "stale",
        reason: "recognized pre-session-start axi-sdk-js plugin",
        remedy: `re-run \`${distributionBinName()} hook install\` from the durable global npm installation`,
      },
    };
  }

  return {
    installed: false,
    compatibility: {
      state: "unmanaged",
      reason: "plugin file does not exactly match a known generated source",
    },
  };
}

function readOpenCodeTargetsStatus(
  targets: HookTargets,
  expectedSource?: string,
): OpenCodeHookStatus {
  const canonical = readOpenCodeHookStatus(targets.opencodePlugin, expectedSource);
  const legacy = readOpenCodeHookStatus(targets.legacyOpencodePlugin);
  const owned = [canonical, legacy].filter((status) => status.installed);
  if (owned.length > 1) {
    return {
      installed: true,
      compatibility: {
        state: "stale",
        reason: "found both canonical and legacy generated OpenCode plugins; exactly one is expected",
        remedy: `re-run \`${distributionBinName()} hook install\` from the durable global npm installation`,
      },
    };
  }
  if (owned.length === 1) return owned[0]!;
  if (
    canonical.compatibility.state === "unmanaged" ||
    legacy.compatibility.state === "unmanaged"
  ) {
    return {
      installed: false,
      compatibility: {
        state: "unmanaged",
        reason: "OpenCode plugin files exist, but none is an exact generated form",
      },
    };
  }
  return canonical;
}

function openCodeClaimPath(path: string): string {
  return `${path}.claim-${process.pid}-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 8)}`;
}

function restoreOpenCodeClaim(claim: string, path: string): void {
  try {
    const entry = lstatSync(claim);
    if (entry.isSymbolicLink()) symlinkSync(readlinkSync(claim), path);
    else if (entry.isFile()) linkSync(claim, path);
    else throw new Error("claimed entry is not a regular file or symlink");
  } catch (error) {
    throw new Error(`OpenCode plugin changed during migration; recovery copy retained at ${collapseHomeDirectory(claim)}`, { cause: error });
  }
  rmSync(claim, { force: true });
}

/** Atomically isolate the current directory entry, then establish ownership on the isolated bytes. */
function claimOwnedOpenCodePlugin(path: string): string | undefined {
  const inspected = readOpenCodeHookStatus(path);
  if (!inspected.installed) return undefined;
  const claim = openCodeClaimPath(path);
  try {
    renameSync(path, claim);
  } catch (error) {
    throw new Error("OpenCode plugin changed after inspection; nothing was removed", { cause: error });
  }
  const claimed = readOpenCodeHookStatus(claim);
  if (!claimed.installed) {
    restoreOpenCodeClaim(claim, path);
    throw new Error("OpenCode plugin changed after inspection; the changed bytes were preserved");
  }
  return claim;
}

function removeOwnedOpenCodePlugin(path: string): boolean {
  const claim = claimOwnedOpenCodePlugin(path);
  if (claim === undefined) return false;
  rmSync(claim, { force: true });
  return true;
}

function installOpenCodePlugin(path: string, next: string): boolean {
  const inspected = readOpenCodeHookStatus(path, next);
  if (inspected.compatibility.state === "unmanaged") {
    throw new Error("refusing to overwrite unmanaged OpenCode plugin");
  }
  if (inspected.compatibility.state === "current") return false;

  const claim = inspected.installed ? claimOwnedOpenCodePlugin(path) : undefined;
  try {
    atomicWriteFileSync(path, next, {
      followFinalSymlink: false,
      expected: {
        destination: null,
        content: null,
        parent: capturePrivateConfigParent(path),
      },
    });
  } catch (error) {
    if (claim !== undefined) restoreOpenCodeClaim(claim, path);
    throw error;
  }
  if (claim !== undefined) rmSync(claim, { force: true });
  return true;
}

/**
 * Re-install prompt signal (consumed by the home render): TRUE when a MANAGED
 * SessionStart hook is installed at any of the given scope bases (default: the cwd project scope
 * and each host's configured global target) whose command predates {@link HOOK_SUBCOMMAND} — i.e. the
 * former home-only hook. Fs-only reads, tolerant of anything malformed; self-clearing (a re-run
 * `hook install` rewrites the command and this goes quiet).
 */
export function hookNeedsUpdate(bases?: string[], deps: HookLocationDeps = {}): boolean {
  for (const targets of targetSets(bases, deps)) {
    for (const p of [targets.claudeSettings, targets.codexHooks]) {
      const s = readHookCompatibilityStatus(readSettings(p));
      if (s.installed && s.compatibility.state !== "current") return true;
    }
    const opencode = readOpenCodeTargetsStatus(targets);
    if (opencode.installed && opencode.compatibility.state !== "current") return true;
  }
  return false;
}

/**
 * True when ANY managed SessionStart hook is installed at any of the given scope bases (default:
 * the cwd project scope and each host's configured global target) — Claude Code settings, Codex hooks, or
 * the OpenCode plugin. Fs-only reads, tolerant of anything malformed. This is the onboarding
 * last-mile signal sync's receipt hints on: no hook anywhere means new sessions never see the
 * board until someone runs `hook install`. (Contrast {@link hookNeedsUpdate}: installed but
 * PREDATING `session-start` — a different, self-clearing prompt on the home render.)
 */
export function hookInstalled(bases?: string[], deps: HookLocationDeps = {}): boolean {
  for (const targets of targetSets(bases, deps)) {
    for (const p of [targets.claudeSettings, targets.codexHooks]) {
      if (readHookCompatibilityStatus(readSettings(p)).installed) return true;
    }
    if (readOpenCodeTargetsStatus(targets).installed) return true;
  }
  return false;
}

