export interface HookStatusInspection {
  targets: HookTargets;
  hosts: {
    claude_code: HookStatus;
    codex: HookStatus;
    opencode: OpenCodeHookStatus;
  };
  displayCommand?: string;
}

/** Read all supported hook hosts through the same exact classifiers as `hook status`. */
export function inspectHookStatus(
  scope: InstallScope,
  deps: Partial<HookDeps> = {},
): HookStatusInspection {
  const targets = deps.base !== undefined
    ? targetsForBase(deps.base, deps.platform)
    : scope === "user"
      ? globalHookTargets(deps.home ?? homedir(), deps.env ?? process.env, deps.platform)
      : targetsForBase(deps.cwd ?? process.cwd(), deps.platform);
  let expectedLaunch = deps.launchSpec;
  try {
    if (!expectedLaunch && deps.commandBase !== undefined) {
      expectedLaunch = {
        program: deps.commandBase,
        args: [HOOK_SUBCOMMAND],
        command: sessionStartHookCommand(deps.commandBase, [HOOK_SUBCOMMAND], deps.platform),
      };
    }
  } catch {
    expectedLaunch = undefined;
  }
  const inspectSettingsTarget = (path: string): HookStatus => {
    const status = readHookCompatibilityStatus(readSettings(path));
    const launchAvailability = inspectHookLaunchAvailability(status.command);
    const preflight = readSettingsForInstall(path);
    if (!preflight.ok) {
      return { ...status, installSafe: false, launchAvailability };
    }
    return { ...status, installSafe: true, launchAvailability };
  };
  const claude = inspectSettingsTarget(targets.claudeSettings);
  const codex = inspectSettingsTarget(targets.codexHooks);
  const opencode = readOpenCodeTargetsStatus(
    targets,
    expectedLaunch
      ? buildOpenCodePluginSource(expectedLaunch.program, expectedLaunch.args)
      : undefined,
  );
  opencode.launchAvailability = inspectHookLaunchAvailability(opencode.command);
  return {
    targets,
    hosts: { claude_code: claude, codex, opencode },
    ...(claude.command ?? expectedLaunch?.command
      ? { displayCommand: claude.command ?? expectedLaunch?.command }
      : {}),
  };
}

/**
 * CLI entry: dispatch the positional subcommand (install|status|uninstall). Output is TOON. An
 * unknown/missing subcommand, or an unsupported --scope, is a USAGE error.
 */
export async function hook(argv: string[], deps: Partial<HookDeps> = {}): Promise<void> {
  const stdout = deps.stdout ?? ((s: string) => void process.stdout.write(s));

  const { values, selection } = parseSelectorOrUsage(
    () =>
      parseArgs({
        args: argv,
        options: {
          scope: { type: "string" },
          "turn-end-sync": { type: "boolean" },
          "git-boards": { type: "boolean" },
          json: { type: "boolean" },
          help: { type: "boolean", short: "h" },
        },
        allowPositionals: true,
      }),
    "hook",
    (positionals) => {
      const [sub, ...data] = positionals;
      if (sub === undefined) return { kind: "unknown" } as const;
      if (sub !== "install" && sub !== "status" && sub !== "uninstall") return { kind: "unknown", token: sub } as const;
      return {
        kind: "selected",
        leaf: sub === "install"
          ? CLI_LEAVES.hookInstall
          : sub === "status"
            ? CLI_LEAVES.hookStatus
            : CLI_LEAVES.hookUninstall,
        data,
        payload: sub,
      } as const;
    },
  );
  if (selection.kind === "help" || selection.kind === "navigation") {
    stdout(renderUsage(HOOK_USAGE));
    return;
  }

  if (selection.kind === "unknown") {
    throw new CliError(
      "USAGE",
      selection.token === undefined
        ? "hook requires a subcommand (install|status|uninstall)"
        : `unknown hook subcommand: ${selection.token} (expected install|status|uninstall)`,
      { help: `${cliInvocation()} hook install|status|uninstall [--scope project|user]` },
    );
  }
  const sub = selection.payload;

  const requestedScope = values.scope as string | undefined;
  const scope = normalizeInstallScope(requestedScope);
  if (scope === undefined) {
    throw new CliError("USAGE", `unsupported hook scope: ${requestedScope} (expected project|user)`, {
      help: `${cliInvocation()} hook ${sub} --scope project|user`,
    });
  }

  const mode = resolveMode(values);
  const turnEndSync = values["turn-end-sync"] === true;
  if (turnEndSync && sub === "status") {
    throw new CliError("USAGE", "--turn-end-sync applies to hook install and hook uninstall; status always reports it", {
      help: `${cliInvocation()} hook status`,
    });
  }
  const gitBoards = values["git-boards"] === true;
  if (gitBoards && (sub !== "install" || !turnEndSync)) {
    throw new CliError("USAGE", "--git-boards applies only to hook install --turn-end-sync", {
      help: `${cliInvocation()} hook install --turn-end-sync --git-boards`,
    });
  }

  if (sub === "status") {
    const inspection = inspectHookStatus(scope, deps);
    const { claude_code: claude, codex, opencode } = inspection.hosts;
    stdout(
      render(
        {
          hook: {
            action: "status",
            scope,
            installed: claude.installed || codex.installed || opencode.installed,
            claude_code: claude.installed,
            codex: codex.installed,
            opencode: opencode.installed,
            turn_end_sync: turnEndStatus(readSettings(inspection.targets.claudeSettings), readSettings(inspection.targets.codexHooks)),
            ...(inspection.displayCommand !== undefined ? { command: inspection.displayCommand } : {}),
            hosts: {
              claude_code: {
                path: collapseHomeDirectory(inspection.targets.claudeSettings),
                state: claude.launchAvailability?.state === "unavailable" ? "unavailable" : claude.compatibility.state,
                compatibility: claude.compatibility,
                launchAvailability: claude.launchAvailability,
              },
              codex: {
                path: collapseHomeDirectory(inspection.targets.codexHooks),
                state: codex.launchAvailability?.state === "unavailable" ? "unavailable" : codex.compatibility.state,
                compatibility: codex.compatibility,
                launchAvailability: codex.launchAvailability,
              },
              opencode: {
                path: collapseHomeDirectory(inspection.targets.opencodePlugin),
                state: opencode.launchAvailability?.state === "unavailable" ? "unavailable" : opencode.compatibility.state,
                compatibility: opencode.compatibility,
                launchAvailability: opencode.launchAvailability,
              },
            },
            targets: {
              claude_code: collapseHomeDirectory(inspection.targets.claudeSettings),
              codex: collapseHomeDirectory(inspection.targets.codexHooks),
              opencode: collapseHomeDirectory(inspection.targets.opencodePlugin),
            },
          },
        },
        mode,
      ),
    );
    return;
  }

  const targets = deps.base !== undefined
    ? targetsForBase(deps.base, deps.platform)
    : scope === "user"
      ? globalHookTargets(deps.home ?? homedir(), deps.env ?? process.env, deps.platform)
      : targetsForBase(deps.cwd ?? process.cwd(), deps.platform);

  if (sub === "install") {
    // Every host that was not installed becomes a structured refusal; the command never emits a
    // success receipt that hides a malformed or unmanaged target.
    const refusals: string[] = [];
    const failTarget = (target: string, err: unknown) =>
      refusals.push(
        `${collapseHomeDirectory(target)}: ${err instanceof Error ? err.message : String(err)} — this target was not installed`,
      );
    // Resolve and validate the one launch BEFORE touching any target. Production npm installs
    // must prove a durable global layout; the command then binds stable prefix paths explicitly.
    let launch: HookLaunchSpec;
    let authority: PersistentInstallAuthority | undefined;
    try {
      if (deps.launchSpec) {
        launch = deps.launchSpec;
      } else if (deps.commandBase !== undefined) {
        launch = {
          program: deps.commandBase,
          args: [HOOK_SUBCOMMAND],
          command: sessionStartHookCommand(deps.commandBase, [HOOK_SUBCOMMAND], deps.platform),
        };
      } else {
        authority =
          deps.installAuthority?.() ?? resolvePersistentInstallAuthority({
            env: deps.env ?? process.env,
            platform: deps.platform,
          });
        if (!authority.allowed) {
          throw new Error(
            `persistent hook install requires a durable npm-global CLI; authority is ${authority.state}: ${authority.reason}`,
          );
        }
        launch = buildHookLaunchSpec(authority, deps.platform);
      }
      if (!isManagedHookCommand(launch.command, deps.platform)) {
        throw new Error(
          `composed hook command ${JSON.stringify(launch.command)} would not be recognized as managed — refusing to install an orphan hook`,
        );
      }
    } catch (err) {
      throw new CliError("RUNTIME", err instanceof Error ? err.message : String(err), {
        ...(authority ? { details: { install_authority: authority } } : {}),
        help: `run npm install -g ${distributionPackageName()}, verify ${distributionBinName()} version --json, then re-run hook install; npx remains supported for read-only/trial commands`,
      });
    }
    const command = launch.command;
    const stopHosts: IntegrationHost[] = [];
    const gitStopHosts: IntegrationHost[] = [];
    const changedByHost: Partial<Record<IntegrationHost, boolean>> = {};
    // Claude Code settings.json + Codex hooks.json: OUR SDK-modeled pure updater, recognizing
    // both managed command forms (see the module header for why the SDK's marker cannot).
    for (const [host, target] of [
      ["claude_code", targets.claudeSettings],
      ["codex", targets.codexHooks],
    ] as const) {
      try {
        const read = readSettingsForInstall(target);
        if (!read.ok) {
          refusals.push(`${collapseHomeDirectory(target)}: ${read.reason} — nothing was written to this file`);
          continue;
        }
        let [updated, changed] = computeSessionStartHookInstall(read.settings, {
          command,
          timeoutSeconds: HOOK_TIMEOUT_SECONDS,
        });
        // An installed Stop hook is kept current by every install; only the flag adds one.
        const wantsStop = turnEndSync || turnEndHookInstalled(read.settings);
        let withGit = false;
        if (wantsStop) {
          const problem = stopShapeProblem(updated);
          if (problem) {
            refusals.push(`${collapseHomeDirectory(target)}: ${problem} — nothing was written to this file`);
            continue;
          }
          // The flag sets the Git opt-in; a plain reinstall keeps what this file already has.
          withGit = turnEndSync ? gitBoards : turnEndHookSyncsGitBoards(read.settings, deps.platform);
          const [withStop, stopChanged] = computeTurnEndHookInstall(updated, {
            command: turnEndHookCommand(launch, deps.platform, { gitBoards: withGit }),
            timeoutSeconds: TURN_END_HOOK_TIMEOUT_SECONDS,
          });
          updated = withStop;
          changed = changed || stopChanged;
        }
        if (changed) writeSettings(target, updated);
        if (wantsStop) stopHosts.push(host);
        if (wantsStop && withGit) gitStopHosts.push(host);
        changedByHost[host] = changed;
      } catch (err) {
        failTarget(target, err);
      }
    }
    // Codex [features].hooks flag (config.toml) — same SDK updater the old installer used.
    const codexConfigPath = targets.codexConfig;
    try {
      const current = existsSync(codexConfigPath) ? readFileSync(codexConfigPath, "utf8") : "";
      const [updated, changed] = computeCodexConfigUpdate(current);
      if (changed) atomicWriteFileSync(codexConfigPath, updated);
      changedByHost.codex = changedByHost.codex === true || changed;
    } catch (err) {
      failTarget(codexConfigPath, err);
    }
    // OpenCode ambient-context plugin — our args-aware source, SDK-marker compatible.
    try {
      const next = buildOpenCodePluginSource(launch.program, launch.args);
      const currentStatus = readOpenCodeHookStatus(targets.opencodePlugin, next);
      if (currentStatus.compatibility.state === "unmanaged") {
        refusals.push(`${collapseHomeDirectory(targets.opencodePlugin)}: refusing to overwrite unmanaged OpenCode plugin`);
      } else {
        const installed = installOpenCodePlugin(targets.opencodePlugin, next);
        const removedLegacy = removeOwnedOpenCodePlugin(targets.legacyOpencodePlugin);
        changedByHost.opencode = installed || removedLegacy;
      }
    } catch (err) {
      failTarget(targets.opencodePlugin, err);
    }
    if (refusals.length > 0) {
      throw new CliError(
        "RUNTIME",
        `hook install failed for ${refusals.length} target(s); other targets were still processed`,
        {
          details: { refused: refusals },
          help: "fix or remove the named file(s), then re-run hook install",
        },
      );
    }
    const lifecycle = integrationChangeReceipt(changedByHost);
    const out: Record<string, unknown> = {
      action: "install",
      scope,
      installed: true,
      command,
      turn_end_sync: stopHosts.length > 0
        ? {
            installed: true,
            hosts: stopHosts,
            command: turnEndHookCommand(launch, deps.platform, { gitBoards: gitStopHosts.length > 0 }),
            ...(gitStopHosts.length > 0 ? { git_boards: gitStopHosts } : {}),
            opt_out: `${cliInvocation()} hook uninstall --turn-end-sync`,
          }
        : { installed: false, opt_in: `${cliInvocation()} hook install --turn-end-sync` },
      ...lifecycle,
      targets: {
        claude_code: collapseHomeDirectory(targets.claudeSettings),
        codex: collapseHomeDirectory(targets.codexHooks),
        opencode: collapseHomeDirectory(targets.opencodePlugin),
      },
    };
    stdout(render({ hook: out }, mode));
    return;
  }

  // uninstall: remove the managed hook from the JSON targets + delete the OpenCode plugin file. The
  // Codex config.toml [features].hooks flag is left in place (harmless; other hooks may rely on it).
  let changed = false;
  const notes: string[] = [];
  for (const path of [targets.claudeSettings, targets.codexHooks]) {
    const settings = readSettings(path);
    const [withoutSessionStart, sessionStartChanged] = turnEndSync ? [settings, false] : computeHookUninstall(settings);
    const [updated, stopChanged] = computeTurnEndHookUninstall(withoutSessionStart);
    if (sessionStartChanged || stopChanged) {
      writeSettings(path, updated);
      changed = true;
    }
  }
  if (turnEndSync) {
    stdout(
      render(
        {
          hook: {
            action: "uninstall",
            scope,
            turn_end_sync: { installed: false },
            changed,
            targets: { claude_code: collapseHomeDirectory(targets.claudeSettings), codex: collapseHomeDirectory(targets.codexHooks) },
          },
        },
        mode,
      ),
    );
    return;
  }
  for (const path of [targets.opencodePlugin, targets.legacyOpencodePlugin]) {
    const openCodeStatus = readOpenCodeHookStatus(path);
    if (openCodeStatus.installed) {
      changed = removeOwnedOpenCodePlugin(path) || changed;
    } else if (openCodeStatus.compatibility.state === "unmanaged") {
      notes.push(`preserved unmanaged OpenCode plugin: ${collapseHomeDirectory(path)}`);
    }
  }
  stdout(
    render(
      {
        hook: {
          action: "uninstall",
          scope,
          installed: false,
          changed,
          ...(notes.length > 0 ? { notes } : {}),
          targets: {
            claude_code: collapseHomeDirectory(targets.claudeSettings),
            codex: collapseHomeDirectory(targets.codexHooks),
            opencode: collapseHomeDirectory(targets.opencodePlugin),
          },
        },
      },
      mode,
    ),
  );
}
