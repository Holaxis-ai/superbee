/** The canonical OpenCode marker. Marker presence alone never establishes ownership. */
export const HOOK_MARKER = "superbee";
const LEGACY_HOOK_MARKER = "agentstate-lite";

/** Backward-compatible command-only ownership predicate, now backed by the exact token classifier. */
export function isManagedHookCommand(command: string, platform: string = process.platform): boolean {
  return isOwnedHookCompatibility(classifyHookCommand(command, platform));
}
/** SessionStart hook timeout, in seconds (matches the SDK default; session-start budgets under it). */
export const HOOK_TIMEOUT_SECONDS = 10;
/** The pull-then-render subcommand the installed hook runs. */
export const HOOK_SUBCOMMAND = "session-start";
/** The end-of-turn subcommand the opt-in Stop hook runs. */
export const TURN_END_SUBCOMMAND = "turn-end";
/** The turn-end flag that also syncs a shared Git board: Git is opt-in, never the default. */
export const TURN_END_GIT_BOARDS_FLAG = "--git-boards";
/** Stop hook timeout, in seconds: above turn-end's own 20-second sync budget. */
export const TURN_END_HOOK_TIMEOUT_SECONDS = 30;
/** The OpenCode plugin filename (SDK naming convention for this marker) and its managed-file marker. */
const OPENCODE_PLUGIN_FILENAME = "axi-superbee.js";
const LEGACY_OPENCODE_PLUGIN_FILENAME = "axi-agentstate-lite.js";
const OPENCODE_MANAGED_MARKER = `axi-sdk-js managed opencode plugin: ${HOOK_MARKER}`;
const LEGACY_OPENCODE_MANAGED_MARKER = `axi-sdk-js managed opencode plugin: ${LEGACY_HOOK_MARKER}`;

/**
 * Compose one generated shell command from an argv vector. Values outside the deliberately safe
 * unquoted character set use POSIX single-argument quoting; OpenCode receives the same vector
 * directly and never invokes a shell.
 *
 * Writer/recognizer contract, asserted HERE in the owning composer: the composed command must
 * satisfy {@link isManagedHookCommand}, or install would write an ORPHAN hook — invisible to
 * status, duplicated by reinstall, stranded by uninstall. An exotic/future channel outside the
 * explicit grammar fails closed here.
 */
export function sessionStartHookCommand(
  base: string = hookCommand(),
  args: string[] = [HOOK_SUBCOMMAND],
  platform: string = process.platform,
): string {
  const command = [base, ...args].map((token) => renderGeneratedHookToken(token, platform)).join(" ");
  if (!isManagedHookCommand(command, platform)) {
    throw new Error(
      `composed hook command ${JSON.stringify(command)} would not be recognized as managed — refusing to install an orphan hook`,
    );
  }
  return command;
}

/**
 * The Stop hook's command: the SessionStart launch with `turn-end` as its subcommand. A command is
 * ours exactly when it ends in `turn-end` and the same launch ending in `session-start` is a
 * recognized generated SessionStart command, so both hooks share one ownership rule.
 */
export function turnEndHookCommand(
  launch: HookLaunchSpec,
  platform: string = process.platform,
  options: { gitBoards?: boolean } = {},
): string {
  const args = [...launch.args.slice(0, -1), TURN_END_SUBCOMMAND, ...(options.gitBoards ? [TURN_END_GIT_BOARDS_FLAG] : [])];
  const command = [launch.program, ...args].map((token) => renderGeneratedHookToken(token, platform)).join(" ");
  if (!isManagedTurnEndCommand(command, platform)) {
    throw new Error(`composed turn-end hook command ${JSON.stringify(command)} would not be recognized as managed`);
  }
  return command;
}

/** The managed turn-end command's tokens up to and including `turn-end`, and whether it opts in to Git boards. */
function managedTurnEndTokens(command: string, platform: string): { tokens: string[]; gitBoards: boolean } | null {
  const all = tokenizeGeneratedHookCommand(command, platform);
  if (!all) return null;
  const gitBoards = all.at(-1) === TURN_END_GIT_BOARDS_FLAG;
  const tokens = gitBoards ? all.slice(0, -1) : all;
  if (tokens.length < 2 || tokens.at(-1) !== TURN_END_SUBCOMMAND) return null;
  return { tokens, gitBoards };
}

export function isManagedTurnEndCommand(command: string, platform: string = process.platform): boolean {
  const managed = managedTurnEndTokens(command, platform);
  if (!managed) return false;
  const sessionStart = [...managed.tokens.slice(0, -1), HOOK_SUBCOMMAND].map((token) => renderGeneratedHookToken(token, platform)).join(" ");
  return isManagedHookCommand(sessionStart, platform);
}

function isManagedTurnEndHook(hook: HookEntry | undefined): boolean {
  return hook?.type === "command" && typeof hook.command === "string" && isManagedTurnEndCommand(hook.command);
}

/** True when an installed managed Stop hook also syncs Git boards (`turn-end --git-boards`). */
export function turnEndHookSyncsGitBoards(settings: HookSettings, platform: string = process.platform): boolean {
  const stop = settings.hooks?.Stop;
  return Array.isArray(stop) && (stop as HookGroupLike[]).some(
    (group) => Array.isArray(group?.hooks) && group.hooks.some(
      (h) => isManagedTurnEndHook(h) && managedTurnEndTokens(h.command!, platform)?.gitBoards === true,
    ),
  );
}

type HookGroupLike = { matcher?: unknown; hooks?: HookEntry[] };

/** Why a settings file's `hooks.Stop` cannot be edited faithfully, or null. */
function stopShapeProblem(settings: HookSettings): string | null {
  const stop = settings.hooks?.Stop;
  if (stop === undefined) return null;
  if (!Array.isArray(stop)) return "`hooks.Stop` exists but is not an array";
  for (const [i, group] of (stop as unknown[]).entries()) {
    if (!isPlainObject(group)) return `\`hooks.Stop[${i}]\` is not an object`;
    if (group.hooks !== undefined && !Array.isArray(group.hooks)) return `\`hooks.Stop[${i}].hooks\` exists but is not an array`;
  }
  return null;
}

/** Pure install of the managed Stop hook: one entry, rewritten in place, duplicates dropped. */
export function computeTurnEndHookInstall(settings: HookSettings, spec: { command: string; timeoutSeconds?: number }): [HookSettings, boolean] {
  const updated = structuredClone(settings);
  const hooks = (updated.hooks ??= {});
  let changed = settings.hooks === undefined;
  const timeout = spec.timeoutSeconds ?? TURN_END_HOOK_TIMEOUT_SECONDS;
  const groups = (Array.isArray(hooks.Stop) ? hooks.Stop : []) as HookGroupLike[];
  if (!Array.isArray(hooks.Stop)) changed = true;
  let rewritten = false;
  const next: HookGroupLike[] = [];
  for (const group of groups) {
    if (!Array.isArray(group?.hooks)) {
      next.push(group);
      continue;
    }
    const kept: HookEntry[] = [];
    for (const h of group.hooks) {
      if (!isManagedTurnEndHook(h)) {
        kept.push(h);
        continue;
      }
      if (rewritten) {
        changed = true;
        continue;
      }
      rewritten = true;
      if (h.command !== spec.command || h.timeout !== timeout) {
        changed = true;
        h.command = spec.command;
        h.timeout = timeout;
      }
      kept.push(h);
    }
    if (kept.length !== group.hooks.length) {
      if (kept.length === 0) continue;
      group.hooks = kept;
    }
    next.push(group);
  }
  if (!rewritten) {
    next.push({ hooks: [{ type: "command", command: spec.command, timeout }] });
    changed = true;
  }
  hooks.Stop = next as typeof hooks.SessionStart;
  return changed ? [updated, true] : [settings, false];
}

/** Pure removal of every managed Stop hook; foreign hooks and groups survive untouched. */
export function computeTurnEndHookUninstall(settings: HookSettings): [HookSettings, boolean] {
  const stop = settings.hooks?.Stop;
  if (!Array.isArray(stop)) return [settings, false];
  const updated = structuredClone(settings);
  let changed = false;
  const next: HookGroupLike[] = [];
  for (const group of updated.hooks!.Stop as HookGroupLike[]) {
    if (!Array.isArray(group?.hooks)) {
      next.push(group);
      continue;
    }
    const kept = group.hooks.filter((h) => !isManagedTurnEndHook(h));
    if (kept.length !== group.hooks.length) {
      changed = true;
      if (kept.length === 0) continue;
      next.push({ ...group, hooks: kept });
    } else next.push(group);
  }
  if (!changed) return [settings, false];
  if (next.length === 0) delete updated.hooks!.Stop;
  else updated.hooks!.Stop = next as NonNullable<HookSettings["hooks"]>["SessionStart"];
  return [updated, true];
}

/** `hook status`'s end-of-turn report: per host, and which hosts also sync Git boards (only when any does). */
function turnEndStatus(claude: HookSettings, codex: HookSettings): Record<string, unknown> {
  const git = { claude_code: turnEndHookSyncsGitBoards(claude), codex: turnEndHookSyncsGitBoards(codex) };
  return {
    claude_code: turnEndHookInstalled(claude),
    codex: turnEndHookInstalled(codex),
    ...(git.claude_code || git.codex ? { git_boards: git } : {}),
  };
}

/** True when the managed Stop hook is installed in this settings file. */
export function turnEndHookInstalled(settings: HookSettings): boolean {
  const stop = settings.hooks?.Stop;
  return Array.isArray(stop) && (stop as HookGroupLike[]).some((group) => Array.isArray(group?.hooks) && group.hooks.some(isManagedTurnEndHook));
}

export interface HookLaunchSpec {
  program: string;
  args: string[];
  command: string;
}

/** Build the one argv-safe launch shared by shell-string hosts and the OpenCode plugin. */
export function buildHookLaunchSpec(
  authority: PersistentInstallAuthority,
  platform: string = process.platform,
): HookLaunchSpec {
  const executable = authority.evidence.executable_path;
  const runtime = authority.evidence.runtime_path;
  if (!authority.allowed || !runtime || !executable) {
    throw new Error(
      `persistent hook launch requires resolved Node and CLI paths; authority is ${authority.state}: ${authority.reason}`,
    );
  }
  const args = [executable, HOOK_SUBCOMMAND];
  const command = sessionStartHookCommand(runtime, args, platform);
  return { program: runtime, args, command };
}

function isManagedHook(
  hook: HookEntry | undefined,
  location: "SessionStart" | "session_start",
  matcher: unknown,
): boolean {
  return isOwnedHookCompatibility(
    classifyHookEntry({
      entry: hook,
      location,
      matcher,
      timeoutSeconds: HOOK_TIMEOUT_SECONDS,
    }),
  );
}

/**
 * Pure install updater for the Claude settings.json / Codex hooks.json SessionStart shape —
 * modeled on the SDK's `computeSessionStartHookUpdate`, but recognizing managed hooks through
 * the exact shared compatibility classifier instead of one substring marker. Rewrites the
 * FIRST managed hook in place (preserving its group position), removes any FURTHER managed hooks
 * (a duplicate left by an older marker mismatch), strips legacy `hooks.session_start` managed
 * entries, and appends a fresh group only when no managed hook exists. Returns
 * [updatedSettings, changed]; an already-correct sole managed hook is a no-op. Foreign hooks and
 * groups survive untouched.
 */
export function computeSessionStartHookInstall(
  settings: HookSettings,
  spec: { command: string; timeoutSeconds?: number },
): [HookSettings, boolean] {
  const updated = structuredClone(settings);
  let changed = false;
  if (!updated.hooks) {
    updated.hooks = {};
    changed = true;
  }
  const hooks = updated.hooks;

  if (Array.isArray(hooks.session_start)) {
    const kept = hooks.session_start.filter((h) => !isManagedHook(h, "session_start", undefined));
    if (kept.length !== hooks.session_start.length) {
      changed = true;
      if (kept.length === 0) delete hooks.session_start;
      else hooks.session_start = kept;
    }
  }

  if (!Array.isArray(hooks.SessionStart)) {
    hooks.SessionStart = [];
    changed = true;
  }
  const timeout = spec.timeoutSeconds ?? HOOK_TIMEOUT_SECONDS;
  let rewritten = false;
  const newGroups: typeof hooks.SessionStart = [];
  for (const group of hooks.SessionStart) {
    // `group?.`: a malformed member (null/primitive) passes through untouched, never throws —
    // the CLI install path refuses such files up front (readSettingsForInstall), but this pure
    // updater must stay total for any direct caller.
    if (!Array.isArray(group?.hooks)) {
      newGroups.push(group);
      continue;
    }
    const keptHooks: HookEntry[] = [];
    for (const h of group.hooks) {
      if (!isManagedHook(h, "SessionStart", group.matcher)) {
        keptHooks.push(h);
        continue;
      }
      if (rewritten) {
        changed = true; // a second managed hook is a duplicate — drop it
        continue;
      }
      rewritten = true;
      if (h.command !== spec.command || h.type !== "command" || h.timeout !== timeout) {
        changed = true;
        h.command = spec.command;
        h.type = "command";
        h.timeout = timeout;
      }
      keptHooks.push(h);
    }
    if (keptHooks.length !== group.hooks.length) {
      if (keptHooks.length === 0) continue; // drop the now-empty group
      group.hooks = keptHooks;
    }
    newGroups.push(group);
  }
  hooks.SessionStart = newGroups;
  if (!rewritten) {
    hooks.SessionStart.push({
      matcher: "",
      hooks: [{ type: "command", command: spec.command, timeout }],
    });
    changed = true;
  }
  return changed ? [updated, true] : [settings, false];
}

/**
 * Pure managed-hook removal (the SDK exports none). Removes every SessionStart hook recognized by
 * the exact shared compatibility classifier, drops any group left with no hooks, and
 * strips legacy hooks.session_start matches. Returns [updatedSettings, changed]; unrelated hooks
 * and groups survive untouched. Shared by the Claude settings.json and the Codex hooks.json
 * (identical HookSettings shape).
 */
export function computeHookUninstall(settings: HookSettings): [HookSettings, boolean] {
  const updated = structuredClone(settings);
  let changed = false;
  const hooks = updated.hooks;
  if (!hooks) return [settings, false];

  if (Array.isArray(hooks.session_start)) {
    const kept = hooks.session_start.filter((h) => !isManagedHook(h, "session_start", undefined));
    if (kept.length !== hooks.session_start.length) {
      changed = true;
      if (kept.length === 0) delete hooks.session_start;
      else hooks.session_start = kept;
    }
  }

  if (Array.isArray(hooks.SessionStart)) {
    const newGroups: typeof hooks.SessionStart = [];
    for (const group of hooks.SessionStart) {
      // Tolerate malformed members (skip untouched, never throw) — same reason as install's updater.
      if (!Array.isArray(group?.hooks)) {
        newGroups.push(group);
        continue;
      }
      const keptHooks = group.hooks.filter((h) => !isManagedHook(h, "SessionStart", group.matcher));
      if (keptHooks.length !== group.hooks.length) {
        changed = true;
        if (keptHooks.length === 0) continue; // drop the now-empty group
        newGroups.push({ ...group, hooks: keptHooks });
      } else {
        newGroups.push(group);
      }
    }
    if (changed) hooks.SessionStart = newGroups;
  }

  return changed ? [updated, true] : [settings, false];
}

export interface HookStatus {
  installed: boolean;
  command?: string;
  compatibility: HookCompatibility;
  /** Read-only install preflight result; omitted by the pure compatibility classifier. */
  installSafe?: boolean;
  launchAvailability?: HookLaunchAvailability;
}

/** Pure status scan over the same exact classifier used by install and uninstall. */
export function readHookCompatibilityStatus(settings: HookSettings): HookStatus {
  const hooks = settings.hooks;
  let sawUnmanaged = false;
  const owned: Array<{ command: string; compatibility: HookCompatibility }> = [];
  if (hooks) {
    if (Array.isArray(hooks.SessionStart)) {
      for (const group of hooks.SessionStart) {
        if (!Array.isArray(group?.hooks)) continue; // tolerate malformed members — report, never throw
        for (const h of group.hooks) {
          const compatibility = classifyHookEntry({
            entry: h,
            location: "SessionStart",
            matcher: group.matcher,
            timeoutSeconds: HOOK_TIMEOUT_SECONDS,
          });
          if (isOwnedHookCompatibility(compatibility)) {
            owned.push({ command: h.command!, compatibility });
            continue;
          }
          if (typeof h?.command === "string") sawUnmanaged = true;
        }
      }
    }
    if (Array.isArray(hooks.session_start)) {
      for (const h of hooks.session_start) {
        const compatibility = classifyHookEntry({
          entry: h,
          location: "session_start",
          timeoutSeconds: HOOK_TIMEOUT_SECONDS,
        });
        if (isOwnedHookCompatibility(compatibility)) {
          owned.push({ command: h.command!, compatibility });
          continue;
        }
        if (typeof h?.command === "string") sawUnmanaged = true;
      }
    }
  }
  if (owned.length > 1) {
    return {
      installed: true,
      command: owned[0]!.command,
      compatibility: {
        state: "stale",
        reason: `found ${owned.length} generated hook entries; exactly one is expected`,
        remedy: `re-run \`${distributionBinName()} hook install\` from the durable global npm installation`,
      },
    };
  }
  if (owned.length === 1) {
    return { installed: true, command: owned[0]!.command, compatibility: owned[0]!.compatibility };
  }
  return {
    installed: false,
    compatibility: sawUnmanaged
      ? { state: "unmanaged", reason: "SessionStart entries exist, but none is an exact generated form" }
      : { state: "absent", reason: "no SessionStart command is configured" },
  };
}

/** Stable legacy projection retained for callers that only need installed + command. */
export function readHookStatus(settings: HookSettings): { installed: boolean; command?: string } {
  const status = readHookCompatibilityStatus(settings);
  return status.command === undefined
    ? { installed: status.installed }
    : { installed: status.installed, command: status.command };
}

