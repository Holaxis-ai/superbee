/** The canonical OpenCode marker. Marker presence alone never establishes ownership. */
export const HOOK_MARKER = "superbee";
const LEGACY_HOOK_MARKER = "agentstate-lite";

/** Backward-compatible command-only ownership predicate, now backed by the exact token classifier. */
export function isManagedHookCommand(command: string): boolean {
  return isOwnedHookCompatibility(classifyHookCommand(command));
}
/** SessionStart hook timeout, in seconds (matches the SDK default; session-start budgets under it). */
export const HOOK_TIMEOUT_SECONDS = 10;
/** The pull-then-render subcommand the installed hook runs. */
export const HOOK_SUBCOMMAND = "session-start";
/** The OpenCode plugin filename (SDK naming convention for this marker) and its managed-file marker. */
const OPENCODE_PLUGIN_FILENAME = "axi-superbee.js";
const LEGACY_OPENCODE_PLUGIN_FILENAME = "axi-agentstate-lite.js";
const OPENCODE_MANAGED_MARKER = `axi-sdk-js managed opencode plugin: ${HOOK_MARKER}`;
const LEGACY_OPENCODE_MANAGED_MARKER = `axi-sdk-js managed opencode plugin: ${LEGACY_HOOK_MARKER}`;

/**
 * Compose one generated shell command from an argv vector. Values outside the deliberately safe
 * unquoted character set use POSIX single-argument quoting; OpenCode receives the same vector
 * directly and never invokes a shell.
 *
 * Writer/recognizer contract, asserted HERE in the owning composer: the composed command must
 * satisfy {@link isManagedHookCommand}, or install would write an ORPHAN hook — invisible to
 * status, duplicated by reinstall, stranded by uninstall. An exotic/future channel outside the
 * explicit grammar fails closed here.
 */
export function sessionStartHookCommand(
  base: string = hookCommand(),
  args: string[] = [HOOK_SUBCOMMAND],
): string {
  const command = [base, ...args].map(renderGeneratedHookToken).join(" ");
  if (!isManagedHookCommand(command)) {
    throw new Error(
      `composed hook command ${JSON.stringify(command)} would not be recognized as managed — refusing to install an orphan hook`,
    );
  }
  return command;
}

export interface HookLaunchSpec {
  program: string;
  args: string[];
  command: string;
}

/** Build the one argv-safe launch shared by shell-string hosts and the OpenCode plugin. */
export function buildHookLaunchSpec(authority: PersistentInstallAuthority): HookLaunchSpec {
  const executable = authority.evidence.executable_path;
  const runtime = authority.evidence.runtime_path;
  if (!authority.allowed || !runtime || !executable) {
    throw new Error(
      `persistent hook launch requires resolved Node and CLI paths; authority is ${authority.state}: ${authority.reason}`,
    );
  }
  const args = [executable, HOOK_SUBCOMMAND];
  const command = sessionStartHookCommand(runtime, args);
  return { program: runtime, args, command };
}

function isManagedHook(
  hook: HookEntry | undefined,
  location: "SessionStart" | "session_start",
  matcher: unknown,
): boolean {
  return isOwnedHookCompatibility(
    classifyHookEntry({
      entry: hook,
      location,
      matcher,
      timeoutSeconds: HOOK_TIMEOUT_SECONDS,
    }),
  );
}

/**
 * Pure install updater for the Claude settings.json / Codex hooks.json SessionStart shape —
 * modeled on the SDK's `computeSessionStartHookUpdate`, but recognizing managed hooks through
 * the exact shared compatibility classifier instead of one substring marker. Rewrites the
 * FIRST managed hook in place (preserving its group position), removes any FURTHER managed hooks
 * (a duplicate left by an older marker mismatch), strips legacy `hooks.session_start` managed
 * entries, and appends a fresh group only when no managed hook exists. Returns
 * [updatedSettings, changed]; an already-correct sole managed hook is a no-op. Foreign hooks and
 * groups survive untouched.
 */
export function computeSessionStartHookInstall(
  settings: HookSettings,
  spec: { command: string; timeoutSeconds?: number },
): [HookSettings, boolean] {
  const updated = structuredClone(settings);
  let changed = false;
  if (!updated.hooks) {
    updated.hooks = {};
    changed = true;
  }
  const hooks = updated.hooks;

  if (Array.isArray(hooks.session_start)) {
    const kept = hooks.session_start.filter((h) => !isManagedHook(h, "session_start", undefined));
    if (kept.length !== hooks.session_start.length) {
      changed = true;
      if (kept.length === 0) delete hooks.session_start;
      else hooks.session_start = kept;
    }
  }

  if (!Array.isArray(hooks.SessionStart)) {
    hooks.SessionStart = [];
    changed = true;
  }
  const timeout = spec.timeoutSeconds ?? HOOK_TIMEOUT_SECONDS;
  let rewritten = false;
  const newGroups: typeof hooks.SessionStart = [];
  for (const group of hooks.SessionStart) {
    // `group?.`: a malformed member (null/primitive) passes through untouched, never throws —
    // the CLI install path refuses such files up front (readSettingsForInstall), but this pure
    // updater must stay total for any direct caller.
    if (!Array.isArray(group?.hooks)) {
      newGroups.push(group);
      continue;
    }
    const keptHooks: HookEntry[] = [];
    for (const h of group.hooks) {
      if (!isManagedHook(h, "SessionStart", group.matcher)) {
        keptHooks.push(h);
        continue;
      }
      if (rewritten) {
        changed = true; // a second managed hook is a duplicate — drop it
        continue;
      }
      rewritten = true;
      if (h.command !== spec.command || h.type !== "command" || h.timeout !== timeout) {
        changed = true;
        h.command = spec.command;
        h.type = "command";
        h.timeout = timeout;
      }
      keptHooks.push(h);
    }
    if (keptHooks.length !== group.hooks.length) {
      if (keptHooks.length === 0) continue; // drop the now-empty group
      group.hooks = keptHooks;
    }
    newGroups.push(group);
  }
  hooks.SessionStart = newGroups;
  if (!rewritten) {
    hooks.SessionStart.push({
      matcher: "",
      hooks: [{ type: "command", command: spec.command, timeout }],
    });
    changed = true;
  }
  return changed ? [updated, true] : [settings, false];
}

/**
 * Pure managed-hook removal (the SDK exports none). Removes every SessionStart hook recognized by
 * the exact shared compatibility classifier, drops any group left with no hooks, and
 * strips legacy hooks.session_start matches. Returns [updatedSettings, changed]; unrelated hooks
 * and groups survive untouched. Shared by the Claude settings.json and the Codex hooks.json
 * (identical HookSettings shape).
 */
export function computeHookUninstall(settings: HookSettings): [HookSettings, boolean] {
  const updated = structuredClone(settings);
  let changed = false;
  const hooks = updated.hooks;
  if (!hooks) return [settings, false];

  if (Array.isArray(hooks.session_start)) {
    const kept = hooks.session_start.filter((h) => !isManagedHook(h, "session_start", undefined));
    if (kept.length !== hooks.session_start.length) {
      changed = true;
      if (kept.length === 0) delete hooks.session_start;
      else hooks.session_start = kept;
    }
  }

  if (Array.isArray(hooks.SessionStart)) {
    const newGroups: typeof hooks.SessionStart = [];
    for (const group of hooks.SessionStart) {
      // Tolerate malformed members (skip untouched, never throw) — same reason as install's updater.
      if (!Array.isArray(group?.hooks)) {
        newGroups.push(group);
        continue;
      }
      const keptHooks = group.hooks.filter((h) => !isManagedHook(h, "SessionStart", group.matcher));
      if (keptHooks.length !== group.hooks.length) {
        changed = true;
        if (keptHooks.length === 0) continue; // drop the now-empty group
        newGroups.push({ ...group, hooks: keptHooks });
      } else {
        newGroups.push(group);
      }
    }
    if (changed) hooks.SessionStart = newGroups;
  }

  return changed ? [updated, true] : [settings, false];
}

export interface HookStatus {
  installed: boolean;
  command?: string;
  compatibility: HookCompatibility;
  /** Read-only install preflight result; omitted by the pure compatibility classifier. */
  installSafe?: boolean;
}

/** Pure status scan over the same exact classifier used by install and uninstall. */
export function readHookCompatibilityStatus(settings: HookSettings): HookStatus {
  const hooks = settings.hooks;
  let sawUnmanaged = false;
  const owned: Array<{ command: string; compatibility: HookCompatibility }> = [];
  if (hooks) {
    if (Array.isArray(hooks.SessionStart)) {
      for (const group of hooks.SessionStart) {
        if (!Array.isArray(group?.hooks)) continue; // tolerate malformed members — report, never throw
        for (const h of group.hooks) {
          const compatibility = classifyHookEntry({
            entry: h,
            location: "SessionStart",
            matcher: group.matcher,
            timeoutSeconds: HOOK_TIMEOUT_SECONDS,
          });
          if (isOwnedHookCompatibility(compatibility)) {
            owned.push({ command: h.command!, compatibility });
            continue;
          }
          if (typeof h?.command === "string") sawUnmanaged = true;
        }
      }
    }
    if (Array.isArray(hooks.session_start)) {
      for (const h of hooks.session_start) {
        const compatibility = classifyHookEntry({
          entry: h,
          location: "session_start",
          timeoutSeconds: HOOK_TIMEOUT_SECONDS,
        });
        if (isOwnedHookCompatibility(compatibility)) {
          owned.push({ command: h.command!, compatibility });
          continue;
        }
        if (typeof h?.command === "string") sawUnmanaged = true;
      }
    }
  }
  if (owned.length > 1) {
    return {
      installed: true,
      command: owned[0]!.command,
      compatibility: {
        state: "stale",
        reason: `found ${owned.length} generated hook entries; exactly one is expected`,
        remedy: "re-run `superbee hook install` from the durable global npm installation",
      },
    };
  }
  if (owned.length === 1) {
    return { installed: true, command: owned[0]!.command, compatibility: owned[0]!.compatibility };
  }
  return {
    installed: false,
    compatibility: sawUnmanaged
      ? { state: "unmanaged", reason: "SessionStart entries exist, but none is an exact generated form" }
      : { state: "absent", reason: "no SessionStart command is configured" },
  };
}

/** Stable legacy projection retained for callers that only need installed + command. */
export function readHookStatus(settings: HookSettings): { installed: boolean; command?: string } {
  const status = readHookCompatibilityStatus(settings);
  return status.command === undefined
    ? { installed: status.installed }
    : { installed: status.installed, command: status.command };
}

