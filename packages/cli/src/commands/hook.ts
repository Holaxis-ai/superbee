function generatedConstant(source: string, name: string): unknown {
  const match = source.match(new RegExp(`^const ${name} = (.+);$`, "m"));
  if (!match) return undefined;
  try {
    return JSON.parse(match[1]!);
  } catch {
    return undefined;
  }
}

/** Exact-source classifier: a marker or familiar substring alone never authorizes mutation. */
function readOpenCodeHookStatus(path: string, expectedSource?: string): OpenCodeHookStatus {
  let entry: ReturnType<typeof lstatSync>;
  try {
    entry = lstatSync(path);
  } catch {
    return { installed: false, compatibility: { state: "absent", reason: "plugin file is absent" } };
  }
  if (entry.isSymbolicLink()) {
    return {
      installed: false,
      compatibility: {
        state: "unmanaged",
        reason: "plugin path is a symlink; generated-plugin ownership requires a regular file",
      },
    };
  }
  if (!entry.isFile()) {
    return { installed: false, compatibility: { state: "unmanaged", reason: "plugin path is not a regular file" } };
  }
  let source: string;
  try {
    source = readFileSync(path, "utf8");
  } catch {
    return { installed: false, compatibility: { state: "unmanaged", reason: "plugin file is unreadable" } };
  }
  if (expectedSource !== undefined && source === expectedSource) {
    return {
      installed: true,
      compatibility: { state: "current", reason: "plugin exactly matches this installation's generator" },
    };
  }

  const command = generatedConstant(source, "command");
  const timeoutMs = generatedConstant(source, "timeoutMs");
  const args = generatedConstant(source, "commandArgs");
  if (
    typeof command === "string" &&
    Array.isArray(args) &&
    args.every((arg) => typeof arg === "string") &&
    typeof timeoutMs === "number" &&
    Number.isInteger(timeoutMs) &&
    source === buildOpenCodePluginSource(command, args as string[], timeoutMs / 1000)
  ) {
    const compatibility = classifyHookCommand(
      [command, ...(args as string[])].map(renderGeneratedHookToken).join(" "),
    );
    if (!isOwnedHookCompatibility(compatibility)) return { installed: false, compatibility };
    if (timeoutMs !== HOOK_TIMEOUT_SECONDS * 1000) {
      return {
        installed: true,
        compatibility: {
          state: "stale",
          reason: "recognized generated plugin has a non-current timeout",
          remedy: "re-run `superbee hook install` from the durable global npm installation",
        },
      };
    }
    return { installed: true, compatibility };
  }

  if (
    typeof command === "string" &&
    Array.isArray(args) &&
    args.every((arg) => typeof arg === "string") &&
    typeof timeoutMs === "number" &&
    Number.isInteger(timeoutMs) &&
    source === buildLegacyOpenCodePluginSource(command, args as string[], timeoutMs / 1000)
  ) {
    const compatibility = classifyHookCommand(
      [command, ...(args as string[])].map(renderGeneratedHookToken).join(" "),
    );
    if (!isOwnedHookCompatibility(compatibility)) return { installed: false, compatibility };
    return {
      installed: true,
      compatibility: {
        state: timeoutMs === HOOK_TIMEOUT_SECONDS * 1000 ? "legacy_identity" : "stale",
        reason: "recognized generated OpenCode plugin uses the legacy ASLite identity",
        remedy: "re-run `superbee hook install` from the durable global npm installation",
      },
    };
  }

  if (
    typeof command === "string" &&
    args === undefined &&
    typeof timeoutMs === "number" &&
    Number.isInteger(timeoutMs) &&
    source === buildLegacySdkOpenCodePluginSource(command, timeoutMs / 1000) &&
    isOwnedHookCompatibility(classifyHookCommand(command))
  ) {
    return {
      installed: true,
      compatibility: {
        state: "stale",
        reason: "recognized pre-session-start axi-sdk-js plugin",
        remedy: "re-run `superbee hook install` from the durable global npm installation",
      },
    };
  }

  return {
    installed: false,
    compatibility: {
      state: "unmanaged",
      reason: "plugin file does not exactly match a known generated source",
    },
  };
}

function readOpenCodeTargetsStatus(
  targets: HookTargets,
  expectedSource?: string,
): OpenCodeHookStatus {
  const canonical = readOpenCodeHookStatus(targets.opencodePlugin, expectedSource);
  const legacy = readOpenCodeHookStatus(targets.legacyOpencodePlugin);
  const owned = [canonical, legacy].filter((status) => status.installed);
  if (owned.length > 1) {
    return {
      installed: true,
      compatibility: {
        state: "stale",
        reason: "found both canonical and legacy generated OpenCode plugins; exactly one is expected",
        remedy: "re-run `superbee hook install` from the durable global npm installation",
      },
    };
  }
  if (owned.length === 1) return owned[0]!;
  if (
    canonical.compatibility.state === "unmanaged" ||
    legacy.compatibility.state === "unmanaged"
  ) {
    return {
      installed: false,
      compatibility: {
        state: "unmanaged",
        reason: "OpenCode plugin files exist, but none is an exact generated form",
      },
    };
  }
  return canonical;
}

/**
 * Re-install prompt signal (consumed by the home render): TRUE when a MANAGED
 * SessionStart hook is installed at any of the given scope bases (default: the cwd project scope
 * and each host's configured global target) whose command predates {@link HOOK_SUBCOMMAND} — i.e. the
 * former home-only hook. Fs-only reads, tolerant of anything malformed; self-clearing (a re-run
 * `hook install` rewrites the command and this goes quiet).
 */
export function hookNeedsUpdate(bases?: string[], deps: HookLocationDeps = {}): boolean {
  for (const targets of targetSets(bases, deps)) {
    for (const p of [targets.claudeSettings, targets.codexHooks]) {
      const s = readHookCompatibilityStatus(readSettings(p));
      if (s.installed && s.compatibility.state !== "current") return true;
    }
    const opencode = readOpenCodeTargetsStatus(targets);
    if (opencode.installed && opencode.compatibility.state !== "current") return true;
  }
  return false;
}

/**
 * True when ANY managed SessionStart hook is installed at any of the given scope bases (default:
 * the cwd project scope and each host's configured global target) — Claude Code settings, Codex hooks, or
 * the OpenCode plugin. Fs-only reads, tolerant of anything malformed. This is the onboarding
 * last-mile signal sync's receipt hints on: no hook anywhere means new sessions never see the
 * board until someone runs `hook install`. (Contrast {@link hookNeedsUpdate}: installed but
 * PREDATING `session-start` — a different, self-clearing prompt on the home render.)
 */
export function hookInstalled(bases?: string[], deps: HookLocationDeps = {}): boolean {
  for (const targets of targetSets(bases, deps)) {
    for (const p of [targets.claudeSettings, targets.codexHooks]) {
      if (readHookCompatibilityStatus(readSettings(p)).installed) return true;
    }
    if (readOpenCodeTargetsStatus(targets).installed) return true;
  }
  return false;
}

/** Injectable filesystem-location and output seams, defaulting to production. */
export interface HookDeps extends HookLocationDeps {
  /** Override all scope targets with one legacy base directory (for focused tests). */
  base: string;
  /** Legacy test seam for one direct command base; production uses install authority. */
  commandBase: string;
  /** Override the complete launch spec (tests). */
  launchSpec: HookLaunchSpec;
  /** Override the one pre-write persistent-install authority (tests). */
  installAuthority: () => PersistentInstallAuthority;
  stdout: (s: string) => void;
}

export interface HookStatusInspection {
  targets: HookTargets;
  hosts: {
    claude_code: HookStatus;
    codex: HookStatus;
    opencode: OpenCodeHookStatus;
  };
  displayCommand?: string;
}

/** Read all supported hook hosts through the same exact classifiers as `hook status`. */
export function inspectHookStatus(
  scope: InstallScope,
  deps: Partial<HookDeps> = {},
): HookStatusInspection {
  const targets = deps.base !== undefined
    ? targetsForBase(deps.base)
    : scope === "user"
      ? globalHookTargets(deps.home ?? homedir(), deps.env ?? process.env)
      : targetsForBase(deps.cwd ?? process.cwd());
  let expectedLaunch = deps.launchSpec;
  try {
    if (!expectedLaunch && deps.commandBase !== undefined) {
      expectedLaunch = {
        program: deps.commandBase,
        args: [HOOK_SUBCOMMAND],
        command: sessionStartHookCommand(deps.commandBase),
      };
    }
  } catch {
    expectedLaunch = undefined;
  }
  const inspectSettingsTarget = (path: string): HookStatus => {
    const status = readHookCompatibilityStatus(readSettings(path));
    const preflight = readSettingsForInstall(path);
    if (!preflight.ok) {
      return { ...status, installSafe: false };
    }
    return { ...status, installSafe: true };
  };
  const claude = inspectSettingsTarget(targets.claudeSettings);
  const codex = inspectSettingsTarget(targets.codexHooks);
  const opencode = readOpenCodeTargetsStatus(
    targets,
    expectedLaunch
      ? buildOpenCodePluginSource(expectedLaunch.program, expectedLaunch.args)
      : undefined,
  );
  return {
    targets,
    hosts: { claude_code: claude, codex, opencode },
    ...(claude.command ?? expectedLaunch?.command
      ? { displayCommand: claude.command ?? expectedLaunch?.command }
      : {}),
  };
}

/**
 * CLI entry: dispatch the positional subcommand (install|status|uninstall). Output is TOON. An
 * unknown/missing subcommand, or an unsupported --scope, is a USAGE error.
 */
export async function hook(argv: string[], deps: Partial<HookDeps> = {}): Promise<void> {
  const stdout = deps.stdout ?? ((s: string) => void process.stdout.write(s));

  const { values, selection } = parseSelectorOrUsage(
    () =>
      parseArgs({
        args: argv,
        options: {
          scope: { type: "string" },
          json: { type: "boolean" },
          help: { type: "boolean", short: "h" },
        },
        allowPositionals: true,
      }),
    "hook",
    (positionals) => {
      const [sub, ...data] = positionals;
      if (sub === undefined) return { kind: "unknown" } as const;
      if (sub !== "install" && sub !== "status" && sub !== "uninstall") return { kind: "unknown", token: sub } as const;
      return {
        kind: "selected",
        leaf: sub === "install"
          ? CLI_LEAVES.hookInstall
          : sub === "status"
            ? CLI_LEAVES.hookStatus
            : CLI_LEAVES.hookUninstall,
        data,
        payload: sub,
      } as const;
    },
  );
  if (selection.kind === "help" || selection.kind === "navigation") {
    stdout(HOOK_USAGE);
    return;
  }

  if (selection.kind === "unknown") {
    throw new CliError(
      "USAGE",
      selection.token === undefined
        ? "hook requires a subcommand (install|status|uninstall)"
        : `unknown hook subcommand: ${selection.token} (expected install|status|uninstall)`,
      { help: `${cliInvocation()} hook install|status|uninstall [--scope project|user]` },
    );
  }
  const sub = selection.payload;

  const requestedScope = values.scope as string | undefined;
  const scope = normalizeInstallScope(requestedScope);
  if (scope === undefined) {
    throw new CliError("USAGE", `unsupported hook scope: ${requestedScope} (expected project|user)`, {
      help: `${cliInvocation()} hook ${sub} --scope project|user`,
    });
  }

  const mode = resolveMode(values);

  if (sub === "status") {
    const inspection = inspectHookStatus(scope, deps);
    const { claude_code: claude, codex, opencode } = inspection.hosts;
    stdout(
      render(
        {
          hook: {
            action: "status",
            scope,
            installed: claude.installed || codex.installed || opencode.installed,
            claude_code: claude.installed,
            codex: codex.installed,
            opencode: opencode.installed,
            ...(inspection.displayCommand !== undefined ? { command: inspection.displayCommand } : {}),
            hosts: {
              claude_code: {
                path: collapseHomeDirectory(inspection.targets.claudeSettings),
                state: claude.compatibility.state,
                compatibility: claude.compatibility,
              },
              codex: {
                path: collapseHomeDirectory(inspection.targets.codexHooks),
                state: codex.compatibility.state,
                compatibility: codex.compatibility,
              },
              opencode: {
                path: collapseHomeDirectory(inspection.targets.opencodePlugin),
                state: opencode.compatibility.state,
                compatibility: opencode.compatibility,
              },
            },
            targets: {
              claude_code: collapseHomeDirectory(inspection.targets.claudeSettings),
              codex: collapseHomeDirectory(inspection.targets.codexHooks),
              opencode: collapseHomeDirectory(inspection.targets.opencodePlugin),
            },
          },
        },
        mode,
      ),
    );
    return;
  }

  const targets = deps.base !== undefined
    ? targetsForBase(deps.base)
    : scope === "user"
      ? globalHookTargets(deps.home ?? homedir(), deps.env ?? process.env)
      : targetsForBase(deps.cwd ?? process.cwd());

  if (sub === "install") {
    // Every host that was not installed becomes a structured refusal; the command never emits a
    // success receipt that hides a malformed or unmanaged target.
    const refusals: string[] = [];
    const failTarget = (target: string, err: unknown) =>
      refusals.push(
        `${collapseHomeDirectory(target)}: ${err instanceof Error ? err.message : String(err)} — this target was not installed`,
      );
    // Resolve and validate the one launch BEFORE touching any target. Production npm installs
    // must prove a durable global layout; the command then binds stable prefix paths explicitly.
    let launch: HookLaunchSpec;
    let authority: PersistentInstallAuthority | undefined;
    try {
      if (deps.launchSpec) {
        launch = deps.launchSpec;
      } else if (deps.commandBase !== undefined) {
        launch = {
          program: deps.commandBase,
          args: [HOOK_SUBCOMMAND],
          command: sessionStartHookCommand(deps.commandBase),
        };
      } else {
        authority =
          deps.installAuthority?.() ?? resolvePersistentInstallAuthority({ env: deps.env ?? process.env });
        if (!authority.allowed) {
          throw new Error(
            `persistent hook install requires a durable npm-global CLI; authority is ${authority.state}: ${authority.reason}`,
          );
        }
        launch = buildHookLaunchSpec(authority);
      }
      if (!isManagedHookCommand(launch.command)) {
        throw new Error(
          `composed hook command ${JSON.stringify(launch.command)} would not be recognized as managed — refusing to install an orphan hook`,
        );
      }
    } catch (err) {
      throw new CliError("RUNTIME", err instanceof Error ? err.message : String(err), {
        ...(authority ? { details: { install_authority: authority } } : {}),
        help: "run `npm install -g superbee`, verify `superbee version --json`, then re-run hook install; npx remains supported for read-only/trial commands",
      });
    }
    const command = launch.command;
    // Claude Code settings.json + Codex hooks.json: OUR SDK-modeled pure updater, recognizing
    // both managed command forms (see the module header for why the SDK's marker cannot).
    for (const target of [targets.claudeSettings, targets.codexHooks]) {
      try {
        const read = readSettingsForInstall(target);
        if (!read.ok) {
          refusals.push(`${collapseHomeDirectory(target)}: ${read.reason} — nothing was written to this file`);
          continue;
        }
        const [updated, changed] = computeSessionStartHookInstall(read.settings, {
          command,
          timeoutSeconds: HOOK_TIMEOUT_SECONDS,
        });
        if (changed) writeSettings(target, updated);
      } catch (err) {
        failTarget(target, err);
      }
    }
    // Codex [features].hooks flag (config.toml) — same SDK updater the old installer used.
    const codexConfigPath = targets.codexConfig;
    try {
      const current = existsSync(codexConfigPath) ? readFileSync(codexConfigPath, "utf8") : "";
      const [updated, changed] = computeCodexConfigUpdate(current);
      if (changed) atomicWriteFileSync(codexConfigPath, updated);
    } catch (err) {
      failTarget(codexConfigPath, err);
    }
    // OpenCode ambient-context plugin — our args-aware source, SDK-marker compatible.
    try {
      const next = buildOpenCodePluginSource(launch.program, launch.args);
      const current = existsSync(targets.opencodePlugin)
        ? readFileSync(targets.opencodePlugin, "utf8")
        : undefined;
      const currentStatus = readOpenCodeHookStatus(targets.opencodePlugin, next);
      if (current !== undefined && currentStatus.compatibility.state === "unmanaged") {
        refusals.push(`${collapseHomeDirectory(targets.opencodePlugin)}: refusing to overwrite unmanaged OpenCode plugin`);
      } else {
        if (current !== next) {
          atomicWriteFileSync(targets.opencodePlugin, next, { followFinalSymlink: false });
        }
        const legacyStatus = readOpenCodeHookStatus(targets.legacyOpencodePlugin);
        if (legacyStatus.installed) {
          rmSync(targets.legacyOpencodePlugin, { force: true });
        }
      }
    } catch (err) {
      failTarget(targets.opencodePlugin, err);
    }
    if (refusals.length > 0) {
      throw new CliError(
        "RUNTIME",
        `hook install failed for ${refusals.length} target(s); other targets were still processed`,
        {
          details: { refused: refusals },
          help: "fix or remove the named file(s), then re-run hook install",
        },
      );
    }
    const out: Record<string, unknown> = {
      action: "install",
      scope,
      installed: true,
      command,
      targets: {
        claude_code: collapseHomeDirectory(targets.claudeSettings),
        codex: collapseHomeDirectory(targets.codexHooks),
        opencode: collapseHomeDirectory(targets.opencodePlugin),
      },
    };
    stdout(render({ hook: out }, mode));
    return;
  }

  // uninstall: remove the managed hook from the JSON targets + delete the OpenCode plugin file. The
  // Codex config.toml [features].hooks flag is left in place (harmless; other hooks may rely on it).
  let changed = false;
  const notes: string[] = [];
  for (const path of [targets.claudeSettings, targets.codexHooks]) {
    const [updated, didChange] = computeHookUninstall(readSettings(path));
    if (didChange) {
      writeSettings(path, updated);
      changed = true;
    }
  }
  for (const path of [targets.opencodePlugin, targets.legacyOpencodePlugin]) {
    const openCodeStatus = readOpenCodeHookStatus(path);
    if (openCodeStatus.installed) {
      rmSync(path, { force: true });
      changed = true;
    } else if (openCodeStatus.compatibility.state === "unmanaged") {
      notes.push(`preserved unmanaged OpenCode plugin: ${collapseHomeDirectory(path)}`);
    }
  }
  stdout(
    render(
      {
        hook: {
          action: "uninstall",
          scope,
          installed: false,
          changed,
          ...(notes.length > 0 ? { notes } : {}),
          targets: {
            claude_code: collapseHomeDirectory(targets.claudeSettings),
            codex: collapseHomeDirectory(targets.codexHooks),
            opencode: collapseHomeDirectory(targets.opencodePlugin),
          },
        },
      },
      mode,
    ),
  );
}
