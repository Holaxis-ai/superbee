// Runs outside the checkout against the installed CLI library.
import assert from "node:assert/strict";
import { openTemporaryViewReader } from "@superbee/cli/temporary-view-reader/v1";
import { openWorkspaceReader } from "@superbee/cli/workspace-reader/v1";

const bundle = process.argv[2];
const html = "\uFEFF<!doctype html><title>Read a document</title>";
const input = { title: "Fixture reader", html, access: "bundle-read" };
const docId = "notes/proof";
const doc = await (await openWorkspaceReader("directory", bundle)).read(docId);
const open = () => openTemporaryViewReader("directory", bundle, input);
const first = await openTemporaryViewReader("catalog", "proof-reader", input);
const second = await open();
assert.equal(first.html, html);
assert.equal(first.title, input.title);
assert.equal(first.access, "bundle-read");
assert.equal(first.contentVersion, second.contentVersion);
await assert.rejects(() => first.renderDocument(docId), { code: "FORBIDDEN" });
await assert.rejects(() => first.decide(true), TypeError);
await assert.rejects(() => first.renderDocument(docId), { code: "FORBIDDEN" });
await first.decide("approve");
const rendered = await first.renderDocument(docId);
assert.equal(rendered.id, docId);
assert.equal(rendered.version, doc.version);
assert.equal(rendered.bounded, false);
assert.match(rendered.html, /<p>portable proof<\/p>/);
await assert.rejects(() => second.renderDocument(docId), { code: "FORBIDDEN" });
await assert.rejects(() => first.renderDocument("notes/missing"), { code: "NOT_FOUND" });
const pendingRead = first.renderDocument(docId);
first.close();
await assert.rejects(pendingRead, error => ["FORBIDDEN", "REVOKED"].includes(error.code));
await assert.rejects(() => first.decide("approve"), /closed or expired/);
await assert.rejects(() => first.renderDocument(docId), { code: "FORBIDDEN" });
await second.decide("deny");
await assert.rejects(() => second.decide("approve"), /closed or expired/);
const fresh = await open();
await assert.rejects(() => fresh.renderDocument(docId), { code: "FORBIDDEN" });
const approving = fresh.decide("approve");
fresh.close();
await assert.rejects(approving, /closed or expired/);
await assert.rejects(() => openTemporaryViewReader("directory", bundle, { ...input, access: "bundle-propose" }), /bundle-read/);
